package io.github.davidnicolini;


public class Main {
    public static void main(String[] args) {

        System.out.println("Primitive Types!");

        float pi = (float) 3.14;
        double size = 123456.789;
        char maritalStatus = 'A';
        boolean approved = true;
        short s = 'a';
        byte b = 1;
        int _variable1 = 123;
        long $variable2 = 123456789;

        System.out.println("float: " + pi);
        System.out.println("double: " + size); 
        System.out.println("char: " + maritalStatus); 
        System.out.println("boolean: " + approved); 
        System.out.println("short: " + s);
        System.out.println("byte: " + b);
        System.out.println("int: " + _variable1);
        System.out.println("long: " + $variable2);
    }
}